function getEmailDomain(email: string) {
	const normalized = email.trim().toLowerCase();
	const at = normalized.lastIndexOf("@");
	if (at < 1 || at === normalized.length - 1) return null;
	return normalized.slice(at + 1);
}

export function isPublicEmailDomain(domain: string) {
	return PUBLIC_EMAIL_DOMAINS.has(domain.trim().toLowerCase());
}

export function sharesInviterCompanyDomain(
	inviterEmail: string | null | undefined,
	inviteeEmail: string,
) {
	if (!inviterEmail) return false;
	const inviterDomain = getEmailDomain(inviterEmail);
	const inviteeDomain = getEmailDomain(inviteeEmail);
	return (
		inviterDomain !== null &&
		inviterDomain === inviteeDomain &&
		!isPublicEmailDomain(inviterDomain)
	);
}
